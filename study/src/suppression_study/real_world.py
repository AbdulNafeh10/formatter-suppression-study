"""Read-only public-archive acquisition and deterministic natural-file sampling."""

from collections import Counter
import hashlib
import io
import json
from pathlib import Path, PurePosixPath
import re
import tarfile
import tokenize
import tomllib
import urllib.request

from .pipeline import ast_signature, save_json

SEED = 20261103
MAX_SOURCE_BYTES = 200 * 1024
EXCLUDED_COMPONENTS = {
    "vendor",
    "vendored",
    "_vendor",
    "third_party",
    "third-party",
    "generated",
}
GENERATED_HEADER = re.compile(
    rb"auto[- ]?generated|generated by|do not edit", re.IGNORECASE
)
NOQA_COMMENT = re.compile(r"#\s*(?:(?:ruff|flake8)\s*:\s*)?noqa\b", re.IGNORECASE)


def safe_member_path(name):
    path = PurePosixPath(name)
    if path.is_absolute() or ".." in path.parts or "\\" in name or ":" in name:
        raise ValueError(f"Unsafe archive member: {name}")
    if len(path.parts) < 2:
        return None
    relative = Path(*path.parts[1:])
    if any(part.endswith((".", " ")) for part in relative.parts):
        raise ValueError(f"Nonportable archive member: {name}")
    return relative


def evaluate_source(path, data, size_limit=MAX_SOURCE_BYTES):
    """Return reasons without importing or executing third-party programs."""
    item = {
        "path": path,
        "size_bytes": len(data),
        "eligible": False,
        "exclusion": None,
        "input_sha256": hashlib.sha256(data).hexdigest(),
        "noqa_comments": [],
        "ai_assisted": False,
    }
    parts = PurePosixPath(path).parts
    if any(part.lower() in EXCLUDED_COMPONENTS for part in parts[:-1]):
        item["exclusion"] = "generated_or_vendored_path"
    elif path.endswith(("_pb2.py", "_pb2_grpc.py")) or GENERATED_HEADER.search(
        data[:4096]
    ):
        item["exclusion"] = "generated_header_or_protobuf"
    elif len(data) > size_limit:
        item["exclusion"] = "source_size_cap"
    else:
        try:
            source = data.decode("utf-8")
            signature = ast_signature(source)
            item["input_structure_sha256"] = hashlib.sha256(
                signature.encode()
            ).hexdigest()
            item["noqa_comments"] = [
                {"row": t.start[0], "column": t.start[1] + 1, "text": t.string}
                for t in tokenize.generate_tokens(io.StringIO(source).readline)
                if t.type == tokenize.COMMENT and NOQA_COMMENT.search(t.string)
            ]
            if item["noqa_comments"]:
                item["eligible"] = True
            else:
                item["exclusion"] = "no_natural_noqa_comment"
        except UnicodeError as exc:
            item.update(exclusion="not_utf8", error=str(exc))
        except (SyntaxError, ValueError, tokenize.TokenError) as exc:
            item.update(
                exclusion="invalid_python311", error=f"{type(exc).__name__}: {exc}"
            )
    item["file_role"] = (
        "tests"
        if any(part in {"tests", "testing"} for part in parts)
        or parts[-1].startswith("test_")
        else (
            "initializer"
            if parts[-1] == "__init__.py"
            else (
                "docs_examples"
                if any(part in {"doc", "docs", "examples"} for part in parts)
                else "package_or_other"
            )
        )
    )
    return item


def rank_population(population, repository, seed=SEED, limit=20):
    eligible = [item for item in population if item["eligible"]]
    eligible.sort(
        key=lambda item: hashlib.sha256(
            f"{seed}:phase4:{repository}:{item['path']}".encode()
        ).hexdigest()
    )
    for rank, item in enumerate(eligible, 1):
        item["rank"] = rank
        item["selected"] = rank <= limit
    return eligible[:limit]


def inspect_archive(archive, spec, output, seed=SEED, limit=20):
    slug = spec["repository"].replace("/", "--")
    context = output / "contexts" / slug
    context.mkdir(parents=True, exist_ok=False)
    population, members_by_path, config_files, license_files = [], {}, [], []
    with tarfile.open(archive, "r:gz") as tar:
        members = tar.getmembers()
        if len(members) > 100000 or sum(m.size for m in members) > 1024**3:
            raise ValueError("Archive exceeds bounded inspection limits")
        for member in members:
            try:
                relative = safe_member_path(member.name)
            except ValueError as exc:
                if member.name.endswith(".py"):
                    population.append(
                        {
                            "path": member.name,
                            "eligible": False,
                            "exclusion": "unsafe_member",
                            "error": str(exc),
                        }
                    )
                continue
            if relative is None:
                continue
            path = relative.as_posix()
            if path in members_by_path:
                raise ValueError(f"Duplicate archive path: {path}")
            members_by_path[path] = member
            if not member.isfile():
                if path.endswith(".py"):
                    population.append(
                        {
                            "path": path,
                            "eligible": False,
                            "exclusion": "nonregular_member",
                        }
                    )
                continue
            if path.endswith(".py"):
                if member.size > MAX_SOURCE_BYTES:
                    population.append(
                        {
                            "path": path,
                            "size_bytes": member.size,
                            "eligible": False,
                            "exclusion": "source_size_cap",
                        }
                    )
                else:
                    data = tar.extractfile(member).read()
                    population.append(evaluate_source(path, data))
            basename = relative.name
            is_license = basename.upper().startswith(("LICENSE", "COPYING", "NOTICE"))
            is_config = (
                relative.suffix in {".toml", ".cfg", ".ini"} or basename == ".gitignore"
            )
            if (is_license or is_config) and member.size <= 2 * 1024**2:
                destination = context / relative
                destination.parent.mkdir(parents=True, exist_ok=True)
                destination.write_bytes(tar.extractfile(member).read())
                (license_files if is_license else config_files).append(path)
        selected = rank_population(population, spec["repository"], seed, limit)
        cases = []
        for item in selected:
            path = item["path"]
            source = output / "sources" / slug / Path(path)
            source.parent.mkdir(parents=True, exist_ok=True)
            source.write_bytes(tar.extractfile(members_by_path[path]).read())
            native_config = find_native_config(context, path)
            cases.append(
                {
                    **item,
                    "case_id": f"{slug}--{hashlib.sha256(path.encode()).hexdigest()[:16]}",
                    "repository": spec["repository"],
                    "repository_url": f"https://github.com/{spec['repository']}",
                    "repository_commit": spec["commit"],
                    "repository_tag": spec["tag"],
                    "source": source.relative_to(output).as_posix(),
                    "source_url": f"https://github.com/{spec['repository']}/blob/{spec['commit']}/{path}",
                    "native_context": context.relative_to(output).as_posix(),
                    "native_config": (
                        native_config.relative_to(output).as_posix()
                        if native_config
                        else None
                    ),
                    "reproduction_selected": path == min(c["path"] for c in selected),
                }
            )
    report = {
        **spec,
        "archive": archive.relative_to(output).as_posix(),
        "archive_sha256": hashlib.sha256(archive.read_bytes()).hexdigest(),
        "python_population": len(population),
        "eligible_noqa_files": sum(p["eligible"] for p in population),
        "selected_files": len(cases),
        "exclusions": dict(
            Counter(p["exclusion"] for p in population if not p["eligible"])
        ),
        "config_files": config_files,
        "license_files": license_files,
        "context_sha256": {
            path: hashlib.sha256((context / path).read_bytes()).hexdigest()
            for path in sorted(config_files + license_files)
        },
        "population": population,
    }
    return report, cases


def find_native_config(context, original_path):
    directory = (context / Path(original_path).parent).resolve()
    context = context.resolve()
    while directory == context or context in directory.parents:
        for name in (".ruff.toml", "ruff.toml", "pyproject.toml"):
            candidate = directory / name
            if not candidate.exists():
                continue
            if name != "pyproject.toml":
                return candidate
            try:
                data = tomllib.loads(candidate.read_text(encoding="utf-8"))
                if "ruff" in data.get("tool", {}):
                    return candidate
            except (ValueError, UnicodeError):
                # Preserve config; parser incompatibility will be visible later.
                if b"[tool.ruff" in candidate.read_bytes():
                    return candidate
        if directory == context:
            break
        directory = directory.parent
    return None


def download_archive(url, destination):
    if not url.startswith("https://codeload.github.com/"):
        raise ValueError("Only immutable GitHub archive URLs are supported")
    request = urllib.request.Request(
        url, headers={"User-Agent": "formatter-suppression-study/phase4"}
    )
    count = 0
    with (
        urllib.request.urlopen(request, timeout=30) as response,
        destination.open("xb") as stream,
    ):
        final_url = response.url
        while chunk := response.read(1024 * 1024):
            count += len(chunk)
            if count > 64 * 1024**2:
                raise ValueError("Archive exceeds 64 MiB download cap")
            stream.write(chunk)
    return {"requested_url": url, "final_url": final_url, "downloaded_bytes": count}


def collect(specification, output):
    spec = json.loads(specification.read_text(encoding="utf-8"))
    output = output.resolve()
    output.mkdir(parents=True, exist_ok=False)
    (output / "archives").mkdir()
    (output / "specification.json").write_bytes(specification.read_bytes())
    reports, cases, failures = [], [], []
    for repo in spec["repositories"]:
        slug = repo["repository"].replace("/", "--")
        archive = output / "archives" / f"{slug}.tar.gz"
        try:
            acquisition = download_archive(repo["archive_url"], archive)
            report, selected = inspect_archive(
                archive, repo, output, spec["seed"], spec["sample_per_repository"]
            )
            report["acquisition"] = acquisition
            save_json(output / f"{slug}.population.json", report)
            reports.append(
                {key: value for key, value in report.items() if key != "population"}
            )
            cases.extend(selected)
            print(
                repo["repository"],
                "python",
                report["python_population"],
                "eligible",
                report["eligible_noqa_files"],
                "selected",
                len(selected),
                flush=True,
            )
        except Exception as exc:
            failure = {
                "repository": repo["repository"],
                "error": f"{type(exc).__name__}: {exc}",
            }
            failures.append(failure)
            save_json(output / f"{slug}.failure.json", failure)
            print(failure, flush=True)
    manifest = {
        "schema_version": 1,
        "phase": 4,
        "dataset_origin": "public-repository-validation",
        "ai_assisted_source_generation": False,
        "seed": spec["seed"],
        "repositories": reports,
        "failures": failures,
        "cases": cases,
    }
    save_json(output / "manifest.json", manifest)
    return manifest
