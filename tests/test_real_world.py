def make_archive(path, entries):
    with tarfile.open(path, "w:gz") as stream:
        for name, data in entries.items():
            member = tarfile.TarInfo(f"root/{name}")
            member.size = len(data)
            stream.addfile(member, io.BytesIO(data))
        link = tarfile.TarInfo("root/link.py")
        link.type = tarfile.SYMTYPE
        link.linkname = "outside.py"
        stream.addfile(link)


def test_archive_preserves_bytes_population_license_and_config(tmp_path):
    source = b"import os  # noqa: F401\r\n"
    archive = tmp_path / "source.tar.gz"
    make_archive(
        archive,
        {
            "pkg/x.py": source,
            "clean.py": b"x=1\n",
            "LICENSE": b"Example license\n",
            "pyproject.toml": b"[tool.ruff]\nline-length = 88\n",
        },
    )
    spec = {"repository": "example/repo", "commit": "a" * 40, "tag": "v1"}
    report, cases = inspect_archive(archive, spec, tmp_path)
    assert report["python_population"] == 3
    assert report["eligible_noqa_files"] == 1
    assert report["exclusions"]["nonregular_member"] == 1
    assert len(cases) == 1
    case = cases[0]
    assert (tmp_path / case["source"]).read_bytes() == source
    assert case["path"] == "pkg/x.py"
    assert case["native_config"].endswith("pyproject.toml")
    assert (
        tmp_path / case["native_context"] / "LICENSE"
    ).read_bytes() == b"Example license\n"
    assert case["reproduction_selected"] is True
    assert case["ai_assisted"] is False
    assert not (tmp_path / case["native_context"] / "link.py").exists()


def test_closest_native_config_and_missing_config(tmp_path):
    assert find_native_config(tmp_path, "pkg/x.py") is None
    (tmp_path / "pyproject.toml").write_text("[tool.ruff]\nline-length=88\n")
    (tmp_path / "pkg").mkdir()
    (tmp_path / "pkg" / "pyproject.toml").write_text('[project]\nname="example"\n')
    assert find_native_config(tmp_path, "pkg/x.py") == tmp_path / "pyproject.toml"
    (tmp_path / "pkg" / ".ruff.toml").write_text("line-length=79\n")
    assert find_native_config(tmp_path, "pkg/x.py") == tmp_path / "pkg" / ".ruff.toml"


def test_actual_native_config_preserves_full_output_and_scopes_matching(tmp_path):
    config = tmp_path / "ruff.toml"
    config.write_text('line-length=30\n[lint]\nselect=["F401", "E501"]\n')
    tail = 'text = "A deliberately long string which should trigger the native E501 diagnostic"\n'
    before = "import os  # noqa: F401\n" + tail
    after = "import os\n" + tail
    result = native_compare(
        before, after, config, tmp_path / "module.py", tmp_path / "native"
    )
    assert result["classification"] == "Newly exposed", result.get("error")
    assert result["newly_exposed_count"] == 1
    assert any(
        d["code"] == "E501" for d in result["full_native_passes"]["A_original_visible"]
    )
    assert result["passes"]["A_original_visible"] == []


def test_actual_native_ignores_are_respected_and_incompatibility_retained(tmp_path):
    config = tmp_path / "ruff.toml"
    config.write_text('[lint]\nselect=["F401"]\nignore=["F401"]\n')
    result = native_compare(
        "import os\n",
        "import os  # noqa\n",
        config,
        tmp_path / "x.py",
        tmp_path / "ignored",
    )
    assert result["classification"] == "Preserved"
    assert result["counts"]["B_original_underlying"] == 0
    config.write_text("unknown-study-setting=true\n")
    result = native_compare(
        "import os\n", "import os\n", config, tmp_path / "x.py", tmp_path / "bad-config"
    )
    assert result["classification"] == "Execution failure"
    assert result["validation_status"] == "failed"
    assert (tmp_path / "bad-config" / "A_original_visible.stderr.txt").exists()


def tiny_dataset(tmp_path):
    dataset = tmp_path / "dataset"
    dataset.mkdir()
    archive = dataset / "source.tar.gz"
    make_archive(
        archive,
        {
            "pkg/x.py": b"import os  # noqa: F401\n",
            "LICENSE": b"Example license\n",
            "pyproject.toml": b'[tool.ruff.lint]\nselect=["F401"]\n',
        },
    )
    spec = {"repository": "example/repo", "commit": "a" * 40, "tag": "v1"}
    report, cases = inspect_archive(archive, spec, dataset)
    save_json(
        dataset / "manifest.json",
        {"seed": 20261103, "repositories": [report], "cases": cases},
    )
    return dataset


def test_actual_world_runner_keeps_primary_native_and_provenance_separate(tmp_path):
    dataset = tiny_dataset(tmp_path)
    output = tmp_path / "results"
    summary = run_real_world(dataset, output)
    assert summary["primary"]["example/repo"]["recorded_comparisons"] == 2
    records = [
        json.loads(line) for line in (output / "results.jsonl").read_text().splitlines()
    ]
    native = [
        json.loads(line)
        for line in (output / "native_results.jsonl").read_text().splitlines()
    ]
    assert len(records) == len(native) == 2
    assert all(r["phase"] == 4 and r["ai_assisted"] is False for r in records)
    assert all(r["repository_commit"] == "a" * 40 for r in records)
    assert all(r["original_path"] == "pkg/x.py" for r in records)
    assert all(r["validation_status"] == "measurement_complete" for r in native)
    assert (output / "native_results.csv").exists()
    assert json.loads((output / "run.json").read_text())["status"] == "complete"
    with pytest.raises(FileExistsError):
        run_real_world(dataset, output)


def test_native_context_tampering_fails_before_measurement(tmp_path):
    dataset = tiny_dataset(tmp_path)
    (dataset / "contexts/example--repo/pyproject.toml").write_text("changed")
    with pytest.raises(ValueError, match="context differs"):
        run_real_world(dataset, tmp_path / "results")
