def test_natural_comments_not_strings_and_no_execution():
    assert not evaluate_source("x.py", b'x = "# noqa: F821"\n')["eligible"]
    source = b'import os  # noqa: F401\nraise RuntimeError("never run")\n'
    result = evaluate_source("src/pkg/x.py", source)
    assert result["eligible"] is True
    assert result["ai_assisted"] is False
    assert result["noqa_comments"][0]["row"] == 1
    assert evaluate_source("x.py", b"# ruff: noqa: F401\nimport os\n")["eligible"]


@pytest.mark.parametrize(
    "path,data,reason",
    [
        ("vendor/x.py", b"# noqa\nx=1\n", "generated_or_vendored_path"),
        ("x_pb2.py", b"# noqa\nx=1\n", "generated_header_or_protobuf"),
        (
            "x.py",
            b"# generated by a tool\n# noqa\nx=1\n",
            "generated_header_or_protobuf",
        ),
        ("x.py", b"# noqa\n\xff", "not_utf8"),
        ("x.py", b"# noqa\nreturn 1\n", "invalid_python311"),
    ],
)
def test_explicit_population_exclusions(path, data, reason):
    result = evaluate_source(path, data)
    assert not result["eligible"]
    assert result["exclusion"] == reason


def test_size_cap_and_sampling_independence_of_order():
    assert (
        evaluate_source("x.py", b"# noqa\nx=1\n", size_limit=1)["exclusion"]
        == "source_size_cap"
    )
    population = [{"path": f"{i}.py", "eligible": True} for i in range(30)]
    a = rank_population(copy.deepcopy(population), "example/repo")
    b = rank_population(list(reversed(copy.deepcopy(population))), "example/repo")
    assert [item["path"] for item in a] == [item["path"] for item in b]
    assert len(a) == 20
    assert a != rank_population(copy.deepcopy(population), "other/repo")


